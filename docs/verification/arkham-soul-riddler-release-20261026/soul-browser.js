async (page) => {
  const base = 'http://127.0.0.1:8897', path = '/arkham/archive/asylum-history/';
  const checks = [], errors = [], requests = [], portraitRequests = [];
  const contexts = [];
  const check = (value, label) => { if (!value) throw Error(label); checks.push(label); console.log('PASS '+label); };
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/chronicle-\d+\.m4a/.test(request.url())) requests.push(request.url()); });
  page.on('request', request => { if (request.url().includes('asylum-history-player-portrait.webp')) portraitRequests.push(request.url()); });
  try {
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base + path);
  await page.locator('.soul-ready').waitFor();
  const audio = page.locator('[data-soul-audio]');
  const play = page.locator('[data-soul-play]');
  const selected = () => page.locator('[data-soul-choice][aria-current=true]').getAttribute('data-soul-choice');
  const seek = async time => {
    await page.locator('[data-soul-seek]').evaluate((el, value) => { el.value = value; el.dispatchEvent(new Event('input', {bubbles:true})); }, String(time));
  };
  check(requests.length === 0, 'entry requests no chronicle audio');
  check(portraitRequests.length===0,'identity portrait not requested on entry');
  check(await audio.getAttribute('src') === null, 'single player has no initial source');
  check(!await page.locator('[data-soul-sequence]').isChecked(), 'sequential play initially off');
  check(!await page.locator('[data-soul-final]').evaluate(el=>el.open), 'final message folded on entry');
  check(!await page.locator('#identity details').evaluate(el=>el.open), 'identity and final scene folded independently');
  await page.waitForFunction(()=>[...document.querySelectorAll('.soul-glyph')].every(el=>el.complete && el.naturalWidth));
  const picture = await page.locator('.soul-art-paper img').evaluate(el=>({width:el.naturalWidth,height:el.naturalHeight}));
  check(picture.width===838 && picture.height===472, 'original menu art loaded without revealing identity portrait');
  check(await page.locator('.soul-glyph').first().evaluate(el=>el.naturalWidth===82 && el.naturalHeight===80), 'native scarab icon excludes next-row pixels');
  for (const width of [320,390,1280,1440]) {
    await page.setViewportSize({width,height:1000});
    if (width<701) await page.locator('[data-soul-directory-toggle]').click();
    await page.locator('[data-soul-choice="1"]').click();
    check(await selected()==='1', width+': row selects record 02');
    check(await audio.getAttribute('src')===null, width+': manual selection does not load or play');
    if(width<701) {
      check(await page.locator('[data-soul-directory]').isHidden(),width+': mobile directory closes after choice');
      check(await page.locator('[data-soul-directory-toggle]').evaluate(el=>el===document.activeElement),width+': focus returns to mobile directory toggle');
    }
    await play.click();
    await page.waitForFunction(()=>document.querySelector('[data-soul-audio]').currentTime>.1);
    await seek(7);
    await page.waitForFunction(()=>document.querySelector('[data-soul-subtitle]').textContent.includes('医生'));
    check(await audio.evaluate(el=>!el.paused), width+': real audio plays and seek updates subtitles');
    await play.click();
    check(await audio.evaluate(el=>el.paused),width+': pause works');
    await page.locator('[data-soul-theme] summary').click();
    check(await page.locator('[data-soul-topic]').isVisible(),width+': current theme expands');
    await page.locator('[data-soul-theme] summary').click();
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),width+': no horizontal overflow');
    await page.locator('[data-soul-player]').scrollIntoViewIfNeeded();
    await page.screenshot({path:'output/playwright/soul-player-'+width+'.png',fullPage:width<701,animations:'disabled'});
    await page.locator('[data-soul-player]').screenshot({path:'output/playwright/soul-panel-'+width+'.png',animations:'disabled'});
    if(width<701) {
      await page.locator('[data-soul-directory-toggle]').click();
      await page.screenshot({path:'output/playwright/soul-directory-'+width+'.png',fullPage:false,animations:'disabled'});
      await page.locator('[data-soul-directory-toggle]').click();
    }
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('[data-soul-choice="0"]').click();
  await page.locator('[data-soul-sequence]').check();
  await play.click();
  await page.waitForFunction(()=>document.querySelector('[data-soul-audio]').currentTime>.1);
  await seek(23.7);
  await page.waitForFunction(()=>document.querySelector('[data-soul-choice="1"]').getAttribute('aria-current')==='true' && document.querySelector('[data-soul-audio]').currentTime>.1);
  check(await audio.evaluate(el=>!el.paused),'real ended event advances and plays next track when enabled');
  await play.click();
  await page.locator('[data-soul-next]').click();
  check(await selected()==='2' && await audio.getAttribute('src')===null,'next changes recording and clears prior audio');
  await page.locator('[data-soul-prev]').click();
  check(await selected()==='1','previous selects prior recording');
  await page.locator('[data-soul-choice="22"]').click();
  check(await page.locator('[data-soul-next]').isDisabled(),'next stops before the final message');
  await play.click();
  await page.waitForFunction(()=>document.querySelector('[data-soul-audio]').currentTime>.1);
  await seek(42.7);
  await page.waitForFunction(()=>document.querySelector('[data-soul-audio]').ended);
  check(await selected()==='22' && await audio.evaluate(el=>el.paused),'sequential play ends at record 23');
  check(!requests.some(url=>url.includes('chronicle-24.')),'final audio never requested by sequential play');
  await page.goto(base+path+'?audit=final#chronicle-24');
  check(!await page.locator('[data-soul-final]').evaluate(el=>el.open),'final deep link does not reveal message');
  check(await selected()==='0','final deep link keeps a safe player selection');
  check(!await page.locator('body').innerText().then(text=>text.includes('昆西·夏普')),'identity absent from visible text');
  await page.locator('[data-soul-final]>summary').click();
  await page.locator('[data-soul-choice="23"]').click();
  check(!await page.locator('#identity details').evaluate(el=>el.open),'choosing final audio does not reveal identity scene');
  check(!await page.locator('[data-soul-illustration]').evaluate(el=>el.classList.contains('is-final')),'selecting final recording alone retains the shadow art');
  await play.click();
  await seek(3);
  await page.waitForFunction(()=>document.querySelector('[data-soul-subtitle]').textContent.includes('昆西·夏普'));
  check(await selected()==='23','final recording plays with its own timed subtitles');
  await page.waitForFunction(()=>document.querySelector('[data-soul-art]').naturalWidth===660);
  check(await page.locator('[data-soul-illustration]').evaluate(el=>el.classList.contains('is-final')),'playing final recording switches to full portrait');
  await page.screenshot({path:'output/playwright/soul-final-portrait-1440.png',fullPage:false,animations:'disabled'});
  await page.locator('[data-soul-final]>summary').click();
  await page.waitForFunction(()=>document.querySelector('[data-soul-choice="22"]').getAttribute('aria-current')==='true');
  check(await audio.getAttribute('src')===null,'closing final disclosure unloads the final audio');
  check(!await page.locator('[data-soul-subtitle]').innerText().then(text=>text.includes('夏普')),'closing final disclosure clears identity subtitles');
  check(!await page.locator('[data-soul-illustration]').evaluate(el=>el.classList.contains('is-final')),'leaving final recording restores shadow art');
  await page.goto(base+path+'#chronicle-19');
  check(await selected()==='18','old record anchor selects requested recording');
  await page.reload();
  check(await selected()==='18','old record anchor survives reload');
  await page.locator('[data-soul-choice="0"]').focus();
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('Enter');
  check(await selected()==='1','icon grid supports arrow navigation and Enter selection');
  await page.locator('[data-soul-seek]').focus();
  await page.keyboard.press('ArrowRight');
  check(await page.locator('[data-soul-seek]').inputValue().then(v=>Number(v)>0),'timeline supports native keyboard seeking');
  await play.click();
  await page.waitForFunction(()=>!document.querySelector('[data-soul-audio]').paused);
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));delete document.hidden;});
  await page.waitForFunction(()=>document.querySelector('[data-soul-audio]').paused);
  check(await audio.evaluate(el=>el.paused),'hidden visibilitychange pauses playback');
  await page.locator('[data-soul-choice="0"]').click();
  await play.click();
  await page.waitForFunction(()=>document.querySelector('[data-soul-audio]').currentTime>.1);
  await page.evaluate(()=>window.dispatchEvent(new PageTransitionEvent('pagehide')));
  check(await audio.getAttribute('src')===null,'pagehide releases audio source');
  const nojs=await page.context().browser().newContext({javaScriptEnabled:false});
  contexts.push(nojs);
  const fallback=await nojs.newPage();await fallback.goto(base+path);
  check(await fallback.locator('[data-soul-choice]:visible').count()===23,'23 native directory entries available without scripts');
  await fallback.locator('#chronicle-01 .soul-fallback summary').click();
  check(await fallback.locator('#chronicle-01 a[href$="chronicle-01.m4a"]').isVisible(),'native recording link available without scripts');
  await fallback.goto(base+path+'#chronicle-24');
  check(!await fallback.locator('[data-soul-final]').evaluate(el=>el.open),'script-free final deep link remains folded');
  await fallback.bringToFront();
  await fallback.locator('[data-soul-final]>summary').focus();
  await fallback.locator('[data-soul-final]>summary').press('Enter');
  await fallback.locator('#chronicle-24 .soul-fallback summary').focus();
  await fallback.locator('#chronicle-24 .soul-fallback summary').press('Enter');
  check(await fallback.locator('#chronicle-24 a[href$="chronicle-24.m4a"]').isVisible(),'final native audio link requires explicit disclosures');
  await nojs.close();
  const denied=await page.context().browser().newContext();
  contexts.push(denied);
  await denied.addInitScript(()=>{Storage.prototype.getItem=Storage.prototype.setItem=()=>{throw Error('denied');};});
  const deniedPage=await denied.newPage();deniedPage.on('pageerror',error=>errors.push(error.message));await deniedPage.goto(base+path);
  await deniedPage.locator('[data-soul-choice="2"]').click();
  check(await deniedPage.locator('[data-soul-choice="2"]').getAttribute('aria-current')==='true','player selection works with denied storage');
  await denied.close();
  check(errors.length===0,'no browser script errors');
  return {count:checks.length,checks,errors,requestedFinalAudio:requests.some(url=>url.includes('chronicle-24.'))};
  } catch (error) {
    return {error:String(error),checks,errors,state:await page.evaluate(()=>({hash:location.hash,title:document.querySelector('[data-soul-title]')?.textContent,audio:document.querySelector('[data-soul-audio]')?.currentTime,ended:document.querySelector('[data-soul-audio]')?.ended,hidden:document.hidden}))};
  } finally {
    for (const context of contexts) await context.close().catch(()=>{});
    await page.bringToFront();
  }
}
