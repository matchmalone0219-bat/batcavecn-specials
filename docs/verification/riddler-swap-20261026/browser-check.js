async (page) => {
  const base='http://127.0.0.1:8895/arkham/archive/riddler/';
  const checks=[],errors=[];
  let releaseTarget=()=>{};
  const check=(value,label)=>{if(!value)throw Error(label);checks.push(label);};
  let context=await page.context().browser().newContext({viewport:{width:1440,height:1000},reducedMotion:'no-preference'});
  let p=await context.newPage();
  p.on('pageerror',e=>errors.push(e.message));
  const trigger=()=>p.locator('[data-riddler-detail] [data-riddler-scan]');
  const figure=()=>p.locator('[data-riddler-detail] .riddler-scan-ready');
  const answer=()=>p.locator('[data-riddler-detail] [data-riddler-solution]');
  const view=(name)=>p.locator('[data-riddler-detail] [data-riddler-view='+name+']');
  const ready=()=>p.waitForFunction(()=>{const i=document.querySelector('[data-riddler-detail] .riddler-scan-scene');return i?.complete&&i.naturalWidth;});
  const targetVisible=()=>p.waitForFunction(()=>document.querySelector('[data-riddler-detail] .riddler-scan-ready')?.classList.contains('is-target'));
  try {
    await p.bringToFront();
    for(const width of [320,390,1280,1440]) for(const [game,id] of [['asylum','asylum-jack-ryder-radio'],['city','city-park-dent-campaign'],['knight','knight-clocktower-empty-suit']]) {
      await p.setViewportSize({width,height:1000});
      await p.goto(base+'?swap='+width+game+'#'+id);await ready();
      await p.locator('[data-riddler-detail] [data-riddler-scan-sound]').uncheck();
      const original=await p.locator('#'+id+' [data-riddler-scan-target] a').getAttribute('href');
      const name=width+' '+game;
      check(await trigger().locator('img').count()===1,name+': only scene mounted initially');
      check(!await view('target').isVisible(),name+': target selector hidden before reveal');
      check(!await answer().evaluate(el=>el.open),name+': solution initially folded');
      await trigger().scrollIntoViewIfNeeded();const box=await trigger().boundingBox();
      await trigger().dblclick({delay:30});await p.waitForTimeout(180);
      check(!await answer().evaluate(el=>el.open),name+': analysis keeps answer folded');
      check(!await figure().evaluate(el=>el.classList.contains('is-target')),name+': target stays hidden during analysis');
      await targetVisible();
      check(await answer().evaluate(el=>el.open),name+': scan reveals explanation');
      const target=trigger().locator('.riddler-scan-target');
      check(await target.evaluate(el=>el.complete&&el.naturalWidth>0),name+': actual target image decodes');
      check(new URL(await target.getAttribute('src')).pathname===original,name+': correct target shown in original frame');
      check(await target.evaluate(el=>getComputedStyle(el).transitionDuration)==='0.25s',name+': quarter-second image fade');
      const after=await trigger().boundingBox();
      check(Math.abs(box.width-after.width)<1&&Math.abs(box.height-after.height)<1,name+': image frame dimensions stay fixed');
      check(await answer().locator('[data-riddler-scan-target], .riddler-scan-target').count()===0,name+': no duplicated target below');
      check(await view('target').getAttribute('aria-pressed')==='true',name+': target selected after scan');
      check(!await answer().locator('.riddler-comic').evaluate(el=>el.open),name+': comic remains folded');
      await p.waitForTimeout(270);
      check(await target.evaluate(el=>getComputedStyle(el).opacity)==='1',name+': target fade completes');
      await trigger().scrollIntoViewIfNeeded();
      await p.screenshot({path:'output/playwright/riddler-swap-'+game+'-'+width+'-target.png'});
      const targetCaption=await figure().locator('figcaption').innerText();
      check(targetCaption.includes('扫描目标'),name+': caption follows target');
      check(new URL(await figure().locator('.riddler-scan-tools>a').getAttribute('href')).pathname===original,name+': original link follows target');
      await view('scene').click();
      check(await view('scene').getAttribute('aria-pressed')==='true'&&await answer().evaluate(el=>el.open),name+': scene comparison keeps answer open');
      check(!await figure().evaluate(el=>el.classList.contains('is-target')),name+': scene comparison restores panorama');
      await view('target').focus();await p.keyboard.press('Enter');
      check(await view('target').getAttribute('aria-pressed')==='true',name+': keyboard switches back to target');
      await trigger().click();await p.waitForTimeout(270);
      check(!await answer().evaluate(el=>el.open)&&!await view('target').isVisible(),name+': image click folds answer and selector');
      check(!await figure().evaluate(el=>el.classList.contains('is-target')),name+': folding restores scene');
      check(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),name+': no horizontal overflow');
    }
    await p.setViewportSize({width:1440,height:1000});
    await p.goto(base+'?swap=summary#asylum-jack-ryder-radio');await ready();
    await trigger().click();await targetVisible();await answer().locator(':scope>summary').click();
    await p.waitForFunction(()=>!document.querySelector('[data-riddler-detail] .riddler-scan-ready').classList.contains('is-target'));
    check(!await figure().evaluate(el=>el.classList.contains('is-target')),'native summary restores scene');
    await trigger().click();await targetVisible();await view('scene').click();await trigger().click();
    check(!await answer().evaluate(el=>el.open),'clicking scene comparison still folds answer');
    await p.route('**/jack-ryder-radio-target.*',route=>route.abort());
    await p.goto(base+'?swap=failed#asylum-jack-ryder-radio');await ready();
    await trigger().click();await p.waitForFunction(()=>document.querySelector('[data-riddler-detail] [data-riddler-solution]').open);
    check(await view('target').isDisabled(),'failed target keeps selector disabled');
    check(!await figure().evaluate(el=>el.classList.contains('is-target')),'failed target preserves scene');
    check((await answer().innerText()).includes('扫描'),'failed target preserves explanation');
    await p.unroute('**/jack-ryder-radio-target.*');
    await trigger().click();await trigger().click();await targetVisible();
    check(true,'failed target can load on a later scan');
    await context.close();
    context=await page.context().browser().newContext({viewport:{width:1440,height:1000},reducedMotion:'no-preference'});
    p=await context.newPage();p.on('pageerror',e=>errors.push(e.message));await p.bringToFront();
    let targetGate=new Promise(resolve=>{releaseTarget=resolve;});
    await p.route('**/city-park-dent-campaign-target.*',async route=>{await targetGate;await route.continue();});
    await p.goto(base+'?swap=slow#city-park-dent-campaign',{waitUntil:'domcontentloaded'});await ready();
    await trigger().click();await p.waitForFunction(()=>document.querySelector('[data-riddler-detail] [data-riddler-solution]').open);
    check(await view('target').isDisabled()&&!await figure().evaluate(el=>el.classList.contains('is-target')),'slow target preserves scene and permits reading explanation');
    releaseTarget();
    await targetVisible();check(true,'slow target fades in when ready');
    await p.unroute('**/city-park-dent-campaign-target.*');
    await context.close();
    context=await page.context().browser().newContext({viewport:{width:1440,height:1000},reducedMotion:'no-preference'});
    p=await context.newPage();p.on('pageerror',e=>errors.push(e.message));await p.bringToFront();
    targetGate=new Promise(resolve=>{releaseTarget=resolve;});
    await p.route('**/city-park-dent-campaign-target.*',async route=>{await targetGate;await route.continue();});
    await p.goto(base+'?swap=cancel#city-park-dent-campaign',{waitUntil:'domcontentloaded'});await ready();await trigger().click();
    await p.locator('#asylum-jack-ryder-radio').click();releaseTarget();await p.waitForTimeout(300);
    check(await trigger().getAttribute('data-riddler-scan')==='asylum'&&!await answer().evaluate(el=>el.open),'late old target does not reveal next question');
    check(!await view('target').isVisible(),'next question keeps target selector hidden');
    await p.unroute('**/city-park-dent-campaign-target.*');
    await p.emulateMedia({reducedMotion:'reduce'});
    await trigger().focus();await p.keyboard.press('Space');
    check(await answer().evaluate(el=>el.open),'reduced motion reveals answer immediately');
    await targetVisible();
    check(await trigger().locator('.riddler-scan-target').evaluate(el=>getComputedStyle(el).transitionDuration)==='0s','reduced motion has no fade');
    const fallbackContext=await page.context().browser().newContext({javaScriptEnabled:false});
    try {
      const fallback=await fallbackContext.newPage();await fallback.goto(base+'#asylum-jack-ryder-radio');
      await fallback.locator('#asylum-jack-ryder-radio [data-riddler-solution]>summary').press('Enter');
      check(await fallback.locator('#asylum-jack-ryder-radio [data-riddler-scan-target]').isVisible(),'no-script target remains in native solution');
    } finally {await fallbackContext.close();}
    check(errors.length===0,'no browser script errors');
    return {count:checks.length,checks,errors};
  } catch(error) {return {error:String(error),checks,errors};}
  finally {releaseTarget();await context.close();await page.bringToFront();}
}
